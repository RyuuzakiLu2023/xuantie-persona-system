"""XTMEM 正文花括号隔断——全库唯一实现（单R4，2026-09-15）。

宿主行为一句话总结：连续双左花括号 + 未注册名 → 抛异常炸整轮；+ 已注册名 → 静默替换篡改正文。
⇒ 判据拦**双左花括号符号本身**，不扫名字形态（名字形态判据实测漏检，见模块头导游图）。

⚠️ 单独的双右花括号经实测**不炸**（插值循环由 indexOf('{{') 驱动）；本模块仍一并隔断，
   属**故意取超集**（2026-09-15 裁定保留）——别照抄成"双右也炸"，那是已被推翻的旧依据。
"""

from __future__ import annotations

import re

# 零宽空格（U+200B）：插在连续同类花括号的相邻两字符之间，使"连续"这一前提不成立
ZWSP = "\u200b"

# 连续同类花括号游程（≥2 个）：左、右分开匹配
# ⚠️ 必须按**游程**处理，不能逐对替换：`{{{`（3个左花括号）逐对替换会留下末尾连续两个，
#    照样被宿主匹配。按游程插隔断可保证输出中【不存在】任何连续同类花括号。
_BRACE_RUN = re.compile(r"\{{2,}|\}{2,}")


def _neutralise_run(m: "re.Match[str]") -> str:
    """把一个连续同类花括号游程打散：n 个同字符 → 相邻者之间各插一个 ZWSP。"""
    run = m.group(0)
    return ZWSP.join([run[0]] * len(run))


def neutralise_template_braces(text: str) -> str:
    """把正文里**连续的同类花括号**用零宽空格隔断，返回新文本（幂等）。

    判据（唯一，不做语法感知）：连续两个及以上左花括号、连续两个及以上右花括号，
    各自在相邻字符之间插入 U+200B。

    性质（守卫测试逐条覆盖）：
      - 幂等：返回值再跑一次结果**字符串全等**（输出中不存在连续同类花括号，故无二次可插点）。
      - 只碰成对符号：单个左/右花括号不动（`{a}`、`{"k":1}` 这类正常内容原样保留）。
      - 不做语法感知：代码块/合法模板一视同仁，一律隔断。
      - 非 str 或空串原样返回（调用方无需先判类型）。

    ⚠️【不】改成"只扫小写名"——宿主触发条件与名字形态无关（中文名/数字开头/空名/大写名/断裂组
    均会触发），精确名口径实测漏检，机制复现见模块头导游图。
    """
    if not isinstance(text, str) or not text:
        return text
    # 快路径：一个花括号都没有就不必跑正则（全库写入必经此处，省一次扫描）
    if "{" not in text and "}" not in text:
        return text
    return _BRACE_RUN.sub(_neutralise_run, text)
